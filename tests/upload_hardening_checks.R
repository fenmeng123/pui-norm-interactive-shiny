# Rewrite only self-generated ZIP members; no external or participant files.
rewrite_book <- function(entry, transform) {
  path <- make_book()
  scratch <- tempfile("pui-test-zip-")
  dir.create(scratch)
  on.exit(unlink(scratch, recursive = TRUE), add = TRUE)
  unzip(path, exdir = scratch)
  xml <- paste(readLines(file.path(scratch, entry), warn = FALSE), collapse = "\n")
  writeLines(transform(xml), file.path(scratch, entry), useBytes = TRUE)
  zip::zipr(path, files = list.files(scratch, recursive = TRUE, all.files = TRUE, no.. = TRUE),
    root = scratch, mode = "mirror", include_directories = FALSE)
  path
}
paths <- c(paths,
