# Use Shiny's own upload writer to test the same paths generated by HTTP upload.
context <- shiny:::FileUploadContext$new()
fixture <- make_book()
upload_copy <- function(path) {
  job <- context$createUploadOperation(list(list(name = "synthetic.xlsx", size = file.info(path)$size, type = "")))
  operation <- context$getUploadOperation(job)
  operation$fileBegin()
  operation$fileChunk(readBin(path, "raw", n = file.info(path)$size))
  operation$fileEnd()
  operation$finish()
}
upload <- upload_copy(fixture)
testServer(server, {
  before <- list.files(tempdir(), pattern = "^pui-workbook-")
  session$setInputs(batch_file = upload)
  stopifnot(isTRUE(batch_review()$ok), !file.exists(upload$datapath), file.exists(fixture))
  # Original upload has gone; repeated download must use separate in-memory copies.
  first <- openxlsx::read.xlsx(output$batch_download, check.names = FALSE, sep.names = " ")
  second <- openxlsx::read.xlsx(output$batch_download, check.names = FALSE, sep.names = " ")
  stopifnot(identical(first, second), identical(first[names(example)], example),
    identical(before, list.files(tempdir(), pattern = "^pui-workbook-")))
})
