example <- data.frame(age = c(10, 15), sex = c("Male", "Female"), score = c(30, 45))
make_book <- function(change = NULL) {
  path <- tempfile(fileext = ".xlsx")
  wb <- openxlsx::createWorkbook()
  openxlsx::addWorksheet(wb, "Data")
  openxlsx::writeData(wb, 1, example)
  if (!is.null(change)) change(wb)
  openxlsx::saveWorkbook(wb, path)
  path
}
paths <- c(
